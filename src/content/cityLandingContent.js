const cityBySlug = Object.fromEntries(CITY_LANDING_PAGES.map((c) => [c.slug, c]))

export const CITY_PAGE_PREFIX = 'petrol-pump-software-'

export function getCityBySlug(slug) {
  if (!slug) return null
  return cityBySlug[slug] || null
}

export function getCityPath(slug) {
  return `/${CITY_PAGE_PREFIX}${slug}`
}

/** Resolve city from full pathname, e.g. /petrol-pump-software-lahore */
export function getCityFromPathname(pathname) {
  const normalized = (pathname || '').replace(/\/+$/, '')
  const prefix = `/${CITY_PAGE_PREFIX}`
  if (!normalized.startsWith(prefix)) return null
  const citySlug = normalized.slice(prefix.length)
  if (!citySlug) return null
  return getCityBySlug(citySlug)
}

