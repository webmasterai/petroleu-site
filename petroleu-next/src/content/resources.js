function isResourcesPageItem(item) {
  return (
    item.published &&
    item.showOnResources !== false &&
    item.mediaType === 'video' &&
    Boolean(item.thumbnailUrl) &&
    Boolean(item.videoUrl) &&
    item.videoUrl !== '#'
  )
}

export function getPublishedResources() {
  return RESOURCES.filter(isResourcesPageItem).sort((a, b) => a.sortOrder - b.sortOrder)
}

export function getHomepageResources() {
  return getPublishedResources()
    .filter((item) => item.showOnHomepage)
    .slice(0, 3)
}

export function getResourceBySlug(slug) {
  return RESOURCES.find((item) => item.slug === slug && item.published) ?? null
}

export function getRelatedResources(current, limit = 3) {
  return getPublishedResources()
    .filter((item) => item.slug !== current.slug)
    .slice(0, limit)
}
